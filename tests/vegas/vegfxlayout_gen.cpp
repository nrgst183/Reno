// vegfxlayout_gen: writes src/vegas/vegfxlayouts.inc, the table of which settings of which OpenFX effects VEGAS keeps as
// whole numbers and which as doubles (see vegfxlayouts.h), from VEGAS's own records in a folder of .veg files.
//
//   vegfxlayout_gen <folder with .veg files> [out.inc]        (default: standard output)
//
// Every effect record (events, tracks, the video output, generated media) is read by the importer; a setting it read as
// a number is whole if its state carries "i" and a double otherwise. A setting seen with both layouts is left out.
// Only effect ids and setting names go into the table (nothing of the projects).
#include "../../src/vegas/vegas.h"
#include "../testdata.h"
#include <cstdio>
#include <map>
#include <set>

using namespace reno;

static std::map<std::string, std::map<std::string, std::set<int>>> g_seen;

static void take(const FxSlot& s)
{
    if (s.kind != "ofx" || s.pluginId.empty()) return;
    for (const auto& m : s.state.get("params").members()) {
        const Json& e = m.second;
        if (!e.has("v")) continue;                  // text and anything unread
        g_seen[s.pluginId][m.first].insert(e.has("i") ? 1 : 0);
    }
}

int main(int argc, char** argv)
{
    if (argc < 2) { std::fprintf(stderr, "usage: vegfxlayout_gen <folder> [out.inc]\n"); return 2; }
    for (const std::string& f : testVegFiles(argv[1])) {
        Project p;
        if (!importVegasProject(f, p).ok) continue;
        for (const auto& s : p.videoOut) take(s);
        for (const auto& m : p.media) if (m.generated) take(m.generator);
        for (const auto& t : p.tracks) {
            for (const auto& s : t.fx) take(s);
            for (const auto& e : t.events) for (const auto& s : e.fx) take(s);
        }
    }
    FILE* out = argc > 2 ? std::fopen(argv[2], "wb") : stdout;
    if (!out) return 3;
    std::fprintf(out, "// Generated by tests/vegas/vegfxlayout_gen.cpp from VEGAS's own effect records: {effect id, setting, 1 = whole number / 0 = double}.\n");
    int n = 0, mixed = 0;
    for (const auto& pl : g_seen)
        for (const auto& pa : pl.second) {
            if (pa.second.size() != 1) { ++mixed; continue; }
            std::string name = pa.first, id = pl.first;
            std::fprintf(out, "{\"%s\", \"%s\", %d},\n", id.c_str(), name.c_str(), *pa.second.begin());
            ++n;
        }
    if (out != stdout) std::fclose(out);
    std::fprintf(stderr, "%d settings of %zu effects (%d left out: seen both ways)\n", n, g_seen.size(), mixed);
    return 0;
}
