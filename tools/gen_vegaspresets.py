#!/usr/bin/env python3
# Makes src/ofx/builtins_vegaspresets.cpp: the presets VEGAS Pro 18 ships (every bundle's Contents/Presets/PresetPackage.xml) for the
# effects named in the second argument (comma separated plugin ids), as pieces of an OfxPresetPackage. builtinPresetPackage() uses them in
# place of Reno's own entries of the same plugin and name, so a VEGAS preset has VEGAS's exact name and values.
#   python3 tools/gen_vegaspresets.py "<path to OFX Video Plug-Ins>" id1,id2,... > src/ofx/builtins_vegaspresets.cpp
import sys, glob, re
import xml.etree.ElementTree as ET
base = sys.argv[1].rstrip('/\\') + '/'
ids = set(sys.argv[2].split(','))
seen = set()
chunks = []
cur = ''
for f in sorted(glob.glob(base + '*/Contents/Presets/PresetPackage.xml')):
    for el in ET.parse(f).getroot().iter('OfxPreset'):
        key = (el.get('plugin'), el.get('name'))
        if key[0] not in ids or key in seen: continue
        seen.add(key)
        s = ET.tostring(el, encoding='unicode')
        s = re.sub(r'>\s+<', '><', s.strip())
        s = re.sub(r'\s+', ' ', s)
        if len(cur) + len(s) > 6000:
            chunks.append(cur); cur = ''
        cur += s + '\n'
if cur: chunks.append(cur)
def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'
print('// GENERATED by tools/gen_vegaspresets.py from VEGAS Pro 18\'s OpenFX preset files. Do not edit.')
print('// VEGAS\'s own presets (exact names and values) for the effects whose presets Reno also wrote by hand in builtins_presets.cpp, or lacked.')
print('#include "builtins_vegaspresets.h"')
print('namespace reno {\nnamespace ofx {\nnamespace builtin {\n')
print('const char* const kVegasPresetChunks[] = {')
for c in chunks: print('  ' + cstr(c) + ',')
print('};')
print('const int kVegasPresetChunkCount = %d;\n' % len(chunks))
print('}  // namespace builtin\n}  // namespace ofx\n}  // namespace reno')
