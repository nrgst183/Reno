#!/usr/bin/env python3
# Makes src/ofx/builtins_magixdata.cpp from VEGAS Pro 18's preset files: the presets for Color Curves, Tiny Planet,
# Mesh Warp and Smart Upscale (builtins_magix.cpp), plus the identity curve set Color Curves starts with. The identity
# curves come from the "Yellow Tint" preset, whose red and green curves are untouched.
#   python3 tools/gen_magixdata.py "<path to OFX Video Plug-Ins>" > src/ofx/builtins_magixdata.cpp
import sys, glob, re, base64, struct
import xml.etree.ElementTree as ET
base = sys.argv[1].rstrip('/\\') + '/'
WANT = ('com.vegascreativesoftware:colorcurves', 'de.magix:stereographicProjectionOCL', 'de.magix:MeshWarp', 'com.sonycreativesoftware:smart_upscale')
chunks = []
default = None
for f in sorted(glob.glob(base + '*/Contents/Presets/*.xml')):
    for el in ET.parse(f).getroot().iter('OfxPreset'):
        if el.get('plugin') not in WANT: continue
        s = ET.tostring(el, encoding='unicode')
        s = re.sub(r'>\s+<', '><', s.strip())
        s = re.sub(r'\s+', ' ', s)
        chunks.append(s + '\n')
        if el.get('name') == 'Yellow Tint' and el.get('plugin') == WANT[0]:
            v = ''.join(el.find('.//OfxParamValue').text.split())
            b = base64.b64decode(v)
            cnt = struct.unpack('<4i', b[4:20])
            assert cnt == (2, 2, 2, 2) and len(b) == 20 + 8 * 104
            c = [b[20 + 208 * i:20 + 208 * (i + 1)] for i in range(4)]
            default = base64.b64encode(b[:20] + c[0] + c[1] + c[0] + c[3]).decode()
def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'
print('// GENERATED by tools/gen_magixdata.py from VEGAS Pro 18\'s OpenFX preset files. Do not edit.')
print('// VEGAS\'s presets for Color Curves, Tiny Planet, Mesh Warp and Smart Upscale (builtins_magix.cpp), as pieces of an')
print('// OfxPresetPackage, and the curves Color Curves starts with.')
print('#include "builtins_magixdata.h"\nnamespace reno {\nnamespace ofx {\nnamespace builtin {\n')
print('const char* const kMagixDefaultCurves =\n  %s;\n' % cstr(default))
print('const char* const kMagixPresetChunks[] = {')
for c in chunks: print('  ' + cstr(c) + ',')
print('};')
print('const int kMagixPresetChunkCount = %d;\n' % len(chunks))
print('}  // namespace builtin\n}  // namespace ofx\n}  // namespace reno')
