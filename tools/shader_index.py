#!/usr/bin/env python3
"""Writes all_arrays.inc and all_table.inc (the <name>.spv.h list used by src/ofx/vkshaderlib.cpp).  Usage: shader_index.py <shaders folder>"""
import os, re, sys
folder = sys.argv[1]
names = sorted(f[:-6] for f in os.listdir(folder) if f.endswith(".spv.h"))
with open(os.path.join(folder, "all_arrays.inc"), "w", newline="\n") as fh:
    fh.write("// Generated by tools/shader_index.py: the shader arrays.\n")
    for n in names:
        fh.write('#include "%s.spv.h"\n' % n)
with open(os.path.join(folder, "all_table.inc"), "w", newline="\n") as fh:
    fh.write("// Generated by tools/shader_index.py: the shader table.\n")
    for n in names:
        fh.write('{"%s", spv_%s, sizeof(spv_%s) / 4},\n' % (n, n, n))
print("%d shaders" % len(names))
