#!/usr/bin/env python3
# Makes src/ofx/builtins_vfxdata.cpp from VEGAS Pro 18's Vfx1.ofx.bundle (Contents/Resources/Vfx1.xml and
# Contents/Presets/PresetPackage.xml): for each effect in WANTED, its parameters (names, labels, defaults, choices) and presets.
#   python3 tools/gen_vfxdata.py "<path to OFX Video Plug-Ins>" > src/ofx/builtins_vfxdata.cpp
import sys, collections, re
import xml.etree.ElementTree as ET
base = sys.argv[1].rstrip('/\\') + '/'
res = ET.parse(base + "Vfx1.ofx.bundle/Contents/Resources/Vfx1.xml").getroot()
pre = ET.parse(base + "Vfx1.ofx.bundle/Contents/Presets/PresetPackage.xml").getroot()
WANTED = sys.argv[2].split(',') if len(sys.argv) > 2 else []
P = 'com.vegascreativesoftware:'

info = {}
for pl in res.iter('OfxPlugin'):
    pid = pl.get('name')
    d = info.setdefault(pid, {'label': '', 'group': '', 'params': collections.OrderedDict()})
    for rs in pl.iter('OfxResourceSet'):
        l = rs.find('OfxPropLabel')
        if l is not None: d['label'] = l.text
        for c in rs.iter('OfxImageEffectContext'):
            for e in c:
                if not e.tag.startswith('OfxParamType'): continue
                lab = e.find('OfxPropLabel')
                opts = [o.text for o in e.findall('OfxParamPropChoiceOption')]
                d['params'][e.get('name')] = {'type': e.tag[len('OfxParamType'):], 'label': lab.text if lab is not None else e.get('name'), 'opts': opts}
presets = collections.OrderedDict()
for p in pre.iter('OfxPreset'):
    vals = collections.OrderedDict()
    for e in p:
        if e.tag.startswith('OfxParamType'):
            vals[e.get('name')] = (e.tag[len('OfxParamType'):], [x.text for x in e.iter('OfxParamValue')])
    presets.setdefault(p.get('plugin'), []).append((p.get('context'), p.get('name'), vals, p))

def num(s):
    try: return float(s)
    except: return 0.0
def fmt(x):
    return ('%g' % x)

def spec(pid):
    plist = presets.get(pid, [])
    meta = info.get(pid, {'label': pid, 'params': {}})
    ctx = plist[0][0] if plist else 'Filter'
    # the default: a preset called Default / (Default) / Simple... else the first
    first = plist[0][2] if plist else {}
    for c, n, v, _ in plist:
        if n.lower().strip('() ') in ('default', 'none', 'reset to none'): first = v; break
    out = []
    names = list(meta['params'].keys())
    for k in first.keys():
        if k not in names: names.append(k)
    for k in names:
        pm = meta['params'].get(k, {})
        t = pm.get('type') or (first[k][0] if k in first else 'Double')
        if k == 'Transition' or t in ('Group', 'Custom', 'PushButton'): continue
        label = pm.get('label') or k
        label = label.replace('|', '/').replace(';', ',')
        vals = [v[k][1] for c, n, v, _ in plist if k in v]
        dv = first[k][1] if k in first else None
        if t in ('Double', 'Integer'):
            flat = [num(x[0]) for x in vals if x] or [0.0]
            d = num(dv[0]) if dv else 0.0
            lo, hi = min(flat + [d]), max(flat + [d])
            rlo = 0.0 if lo >= 0 else lo * 2 - 1
            rhi = 1.0 if hi <= 1 else hi * 2
            if t == 'Integer': rlo, rhi = (int(rlo) if lo >= 0 else int(rlo)), int(max(rhi, 1))
            out.append('%s|%s|%s|%s|%s|%s' % ('D' if t == 'Double' else 'I', k, label, fmt(d), fmt(rlo), fmt(rhi)))
        elif t == 'Boolean':
            out.append('B|%s|%s|%d' % (k, label, 1 if dv and dv[0] == 'true' else 0))
        elif t == 'Choice':
            opts = pm.get('opts') or []
            if not opts:
                mx = max([int(num(x[0])) for x in vals if x] + [1])
                opts = ['Choice %d' % (i + 1) for i in range(mx + 1)]
            out.append('C|%s|%s|%d|%s' % (k, label, int(num(dv[0])) if dv else 0, ','.join(o.replace(',', ' ').replace('|', '/') for o in opts)))
        elif t in ('RGBA', 'RGB'):
            comps = (dv[0].split() if dv else ['0', '0', '0', '1'])
            out.append('%s|%s|%s|%s' % ('K' if t == 'RGBA' else 'R', k, label, ' '.join(comps)))
        elif t == 'Double2D':
            comps = (dv[0].split() if dv else ['0.5', '0.5'])
            out.append('P|%s|%s|%s' % (k, label, ' '.join(comps)))
        elif t == 'String':
            out.append('S|%s|%s|%s' % (k, label, (dv[0] or '') if dv else ''))
    return meta['label'], ctx, ';'.join(out)

def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'

print('// GENERATED by tools/gen_vfxdata.py from VEGAS Pro 18\'s Vfx1.ofx.bundle (resource and preset files). Do not edit.')
print('// The parameters of the VEGAS stock effects Reno has stand-ins for: "kind|name|label|default...;..." (see builtins_more.cpp),')
print('// and the presets VEGAS ships for them (an OfxPresetPackage, in pieces).')
print('#include "builtins_vfxdata.h"\nnamespace reno {\nnamespace ofx {\nnamespace builtin {\n')
print('const VfxSpec kVfxSpecs[] = {')
for w in WANTED:
    pid = P + w
    label, ctx, sp = spec(pid)
    print('  {%s, %s, %s, %s},' % (cstr(pid), cstr(label.replace('VEGAS ', '', 1) if label.startswith('VEGAS ') else label), cstr(ctx), cstr(sp)))
print('};')
print('const int kVfxSpecCount = %d;\n' % len(WANTED))
# presets, in pieces of < 6000 characters
chunks = []
cur = ''
for w in WANTED:
    pid = P + w
    for c, n, v, el in presets.get(pid, []):
        if any(t == 'Custom' for t, _ in v.values()): continue
        s = ET.tostring(el, encoding='unicode')
        s = re.sub(r'>\s+<', '><', s.strip())
        s = re.sub(r'\s+', ' ', s)
        if len(cur) + len(s) > 6000:
            chunks.append(cur); cur = ''
        cur += s + '\n'
if cur: chunks.append(cur)
print('const char* const kVfxPresetChunks[] = {')
for c in chunks: print('  ' + cstr(c) + ',')
print('};')
print('const int kVfxPresetChunkCount = %d;\n' % len(chunks))
print('}  // namespace builtin\n}  // namespace ofx\n}  // namespace reno')
