#!/usr/bin/env python3
# Makes src/ofx/builtins_colordata.cpp from VEGAS Pro 18's OpenFX preset files: the AutoLooks and Color Match presets.
# The Color Match presets spell the lightness switch "ProcessLightness" but the plug-in declares "Processlightness", so it is renamed here.
#   python3 tools/gen_colordata.py "<path to OFX Video Plug-Ins>" > src/ofx/builtins_colordata.cpp
import sys, glob, re
import xml.etree.ElementTree as ET
base = sys.argv[1].rstrip('/\\') + '/'
WANT = ('com.vegascreativesoftware:autolooks', 'com.vegascreativesoftware:colormatch', 'com.vegascreativesoftware:lutfilter', 'com.vegascreativesoftware:colorgrading')
chunks = []
for f in sorted(glob.glob(base + '*/Contents/Presets/*.xml')):
    for el in ET.parse(f).getroot().iter('OfxPreset'):
        if el.get('plugin') not in WANT: continue
        s = ET.tostring(el, encoding='unicode')
        s = re.sub(r'>\s+<', '><', s.strip())
        s = re.sub(r'\s+', ' ', s)
        s = s.replace('name="ProcessLightness"', 'name="Processlightness"')
        chunks.append(s + '\n')
def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'
print('// GENERATED by tools/gen_colordata.py from VEGAS Pro 18\'s OpenFX preset files. Do not edit.')
print('// VEGAS\'s presets for AutoLooks and Color Match (builtins_color.cpp), as pieces of an OfxPresetPackage.')
print('#include "builtins_colordata.h"\nnamespace reno {\nnamespace ofx {\nnamespace builtin {\n')
print('const char* const kColorPresetChunks[] = {')
for c in chunks: print('  ' + cstr(c) + ',')
print('};')
print('const int kColorPresetChunkCount = %d;\n' % len(chunks))
print('}  // namespace builtin\n}  // namespace ofx\n}  // namespace reno')
